export function getQuest(index: number): ChainQuest | null {
  if (index < 0 || index >= 1000) return null;
  const example = EXAMPLES[index % EXAMPLES.length]!;
  const tier: ChainQuest["tier"] = example.count >= 100 ? "hard" : example.count >= 34 ? "medium" : "easy";
  const tierLabel = tier === "hard" ? "Сложное" : tier === "medium" ? "Среднее" : "Лёгкое";
  return {
    index,
    number: index + 1,
    circle: Math.floor(index / 10) + 1,
    tier,
    tierLabel,
    dhikrId: example.dhikrId,
    count: example.count,
    who: example.who,
    lead: `Повтори за: ${example.who}`,
    story: example.story,
  };
}

