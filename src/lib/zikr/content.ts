export function dhikrById(id: string): Dhikr {
  const found = DHIKR.find((d) => d.id === id);
  if (found) return found;
  const name = ALLAH_NAMES.find((n) => n.id === id);
  if (name) {
    return {
      id: name.id,
      arabic: name.arabic,
      name: name.name,
      short: name.name,
      meaning: name.meaning,
      primary: false,
      reward: "У Аллах1а девяносто девять имён. Кто сохранит их, войдёт в Рай.",
      source: "аль-Бухари, Муслим",
    };
  }
  return DHIKR[0]!;
}

